    // 공격이 맞는 순간. 이 순간 한 번 판정한다. 판정 지속 공격은 이 순간부터 그 단계가 끝날 때까지 판정한다.
    Hit,
    // 공격 경직 저항이 풀리는 순간. 경직 저항을 이벤트까지 유지하는 공격에서만 쓴다.
    ResistEnd
}
