// 적 공격 클립에 찍는 애니메이션 이벤트 종류. 클립의 이벤트 Function 이름과 같은 이름을 쓴다.
public enum EnemyAnimationEventType
{
    // 패링 공격의 예고가 시작되는 순간. 이 순간 예고 표시를 켜고 패링 가능 시간을 연다. 패링 공격의 준비 단계 클립에 넣는다.
    Telegraph,
    // 판정이 시작되는 순간. 한 순간 판정 동작은 이 순간 한 번 판정하고, 구간 판정 동작은 이 순간부터 그 동작이 끝날 때까지 판정한다.
    HitStart,
    // 구간 판정 동작의 판정이 끝나는 순간. 없으면 그 동작이 끝날 때까지 판정한다.
    HitEnd,
    // 공격 경직 저항이 풀리는 순간. 경직 저항을 이벤트까지 유지하는 공격에서만 쓴다.
    ResistEnd,
    // 도약 · 돌진 이동이 시작되는 순간. 이 순간부터 같은 클립의 LeapEnd 이벤트까지 목표 지점으로 이동한다.
    LeapStart,
    // 도약 · 돌진의 목표 지점을 고정하는 순간. 그 전까지는 목표 지점이 대상을 따라간다. 없으면 LeapEnd 까지 따라간다.
    LeapLock,
    // 도약 · 돌진 이동이 끝나는 순간(착지 · 도착). 판정은 이 이벤트와 별개로 Hit 이벤트가 정한다.
    LeapEnd
}
