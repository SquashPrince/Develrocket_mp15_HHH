// 플레이어 클립에 찍는 애니메이션 이벤트 종류. 클립의 이벤트 Function 이름과 같은 이름을 쓴다.
public enum PlayerAnimationEventType
{
    // 이 시점부터 누른 공격은 저장했다가 공격 동작이 끝나면 다음 단계로 이어간다.
    ComboInputOpen,
    // 판정 시작. 구간 판정 동작은 판정을 켜고, 한 순간 판정 동작은 이 순간 한 번 판정한다.
    HitStart,
    // 판정 끝. 구간 판정 동작의 판정을 끈다. 강타로 끝나는 구간이면 찍지 않고 강타 끝을 찍는다.
    HitEnd,
    // 강타 끝. 이 순간 강타 판정을 한 번 하고 판정을 끈다. 그로기 적에게 맞으면 콤보 스킬이 발동한다.
    ImpactEnd,
    // 휘두르기가 끝나고 후딜(자세를 되돌리는 구간)이 시작되는 지점
    AttackMotionEnd,
    // 후딜이 끝나 대기 자세로 돌아온 지점
    RecoveryEnd
}
